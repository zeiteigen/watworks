export function operationFailure(error: unknown, phase: OperationPhase, mutationAttempted: boolean): OperationFailure {
  if (error instanceof BrowserOperationError) return error.failure;
  const message = error instanceof Error && (safeMessages.has(error.message) || /^Applications list request changed \(literal declarations: \d+, list candidates: \d+\)$/.test(error.message)) ? error.message
    : error instanceof Error && /No tab with id|No frame with id|The tab was closed|Frame.*was removed/.test(error.message) ? "Browser tab or frame closed during the operation"
    : error instanceof Error && /Cannot access contents of|Missing host permission/.test(error.message) ? "Browser denied access to the WaterlooWorks page"
    : error instanceof Error && /^(TypeError|ReferenceError|SyntaxError|NotAllowedError|SecurityError)$/.test(error.name)
      ? `${error.name} in browser operation` : "Unexpected operation error (details withheld)";
  return { phase, code: mutationAttempted ? "outcome_unknown" : "no_remote_mutation", message };
}
