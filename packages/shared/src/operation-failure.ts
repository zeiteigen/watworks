import { z } from "zod";

/** Only bounded diagnostic metadata crosses the broker; never page HTML or PDF contents. */
export const operationFailureSchema = z.object({
  phase: z.enum(["preflight", "reservation", "upload_inventory", "upload_entry", "upload_form", "upload_file", "upload_save", "upload_verify", "staging", "search", "posting", "apply", "wizard", "fill", "advance", "submit", "verify", "transport"]),
  code: z.enum(["no_remote_mutation", "outcome_unknown"]),
  message: z.string().min(1).max(300),
}).strict();
export type OperationFailure = z.infer<typeof operationFailureSchema>;
export type OperationPhase = OperationFailure["phase"];

const OPERATION_FAILURE_PREFIX = "[waterlooworks-operation-failure]";

/** Encode bounded metadata inside the existing error string for older brokers to forward. */
export function encodeOperationFailure(failure: OperationFailure): string {
  const validated = operationFailureSchema.parse(failure);
  return `${OPERATION_FAILURE_PREFIX}${JSON.stringify(validated)}\n${validated.phase}: ${validated.message}`;
}

/** Decode only a prefixed, schema-valid failure payload; ordinary errors remain ordinary. */
export function decodeOperationFailure(message: string): OperationFailure | undefined {
  if (!message.startsWith(OPERATION_FAILURE_PREFIX)) return undefined;
  const end = message.indexOf("\n", OPERATION_FAILURE_PREFIX.length);
  if (end < 0) return undefined;
  try {
    const parsed: unknown = JSON.parse(message.slice(OPERATION_FAILURE_PREFIX.length, end));
    const result = operationFailureSchema.safeParse(parsed);
    return result.success ? result.data : undefined;
  } catch {
    return undefined;
  }
}

export class BrowserOperationError extends Error {
  constructor(public readonly failure: OperationFailure, cause?: unknown) {
    super(`${failure.phase}: ${failure.message}`, cause === undefined ? undefined : {cause});
    this.name = "BrowserOperationError";
  }
}

